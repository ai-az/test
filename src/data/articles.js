// أرقام المواد المُدخَلة فعلياً، مرتّبة — تُستخدم للتنقّل السابق/التالي.
export const enteredArticleNumbers = Object.values(articles)
  .filter((a) => a.status === "entered")
  .map((a) => a.articleNumber)
  .sort((a, b) => a - b);

export const getArticle = (n) => articles[Number(n)] || null;

export const getAdjacentArticle = (n, dir) => {
  const idx = enteredArticleNumbers.indexOf(Number(n));
  if (idx === -1) return null;
  const next = enteredArticleNumbers[idx + (dir === "next" ? 1 : -1)];
  return next ?? null;
};

export const articlesInChapter = (chapterNumber) =>
  Object.values(articles)
    .filter((a) => a.chapter.number === Number(chapterNumber))
    .sort((a, b) => a.articleNumber - b.articleNumber);
